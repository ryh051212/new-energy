import test from 'node:test'
import assert from 'node:assert/strict'
import { ANGEL_CENTER, createAngelCity, nearbyModelStations, stationModel, modelVehicle, simulateCharging, simulationFrame, compareChargingScenarios } from '../src/utils/angelCity.js'
const station=(id,properties={},coordinates=ANGEL_CENTER)=>({type:'Feature',properties:{id,name:id,coordSystem:'WGS84',...properties},geometry:{type:'Point',coordinates}})

test('model has distinct low-rise, high-rise, and landmark volumes; closed footprints and stable geometry',()=>{
  const scene=createAngelCity()
  assert.deepEqual(scene,createAngelCity())
  const buildings=scene.buildings.features.filter(f=>f.properties.base===0)
  assert.ok(buildings.some(f=>f.properties.height<=15))
  assert.ok(buildings.some(f=>f.properties.height>=80))
  assert.ok(buildings.some(f=>f.properties.kind==='mall'))
  for(const f of scene.buildings.features) assert.deepEqual(f.geometry.coordinates[0][0],f.geometry.coordinates[0].at(-1))
})
test('station filtering normalizes GCJ coordinates, excludes synthetic/malformed/far points, and deduplicates',()=>{
  const gcj=station('gcj',{coordSystem:'GCJ-02'},[113.846681,34.03593])
  const rows=nearbyModelStations([gcj,station('gcj'),station('far',{},[110,30]),station('demo',{isSynthetic:true}),station('bad',{},[NaN,34])],800)
  assert.equal(rows.length,1)
  assert.deepEqual(rows[0].geometry.coordinates,ANGEL_CENTER)
  assert.equal(rows[0].properties.coordSystem,'WGS84')
})
test('unknown and simulated capacity are assumptions, while known zero and access restrictions remain effective',()=>{
  const f=station('a',{pileCount:30,powerKw:180,simulatedFields:['pileCount','powerKw']})
  assert.equal(stationModel(f).piles,8)
  assert.equal(stationModel(f).power,60)
  assert.equal(stationModel(f).assumed,true)
  assert.equal(stationModel(station('b',{pileCount:0,powerKw:120})).piles,0)
  assert.equal(stationModel(station('c',{accessAllowed:false}),{enabled:true}).enabled,false)
  assert.equal(stationModel(station('d',{status:'closed'}),{enabled:true}).enabled,false)
  assert.equal(stationModel(station('e',{chargingCurrentTypes:['AC']}),{enabled:true},{chargingRequirement:'DC'}).enabled,false)
  assert.equal(stationModel(station('f'),{piles:-2}).piles,0)
  assert.equal(stationModel(station('f'),{piles:1e5}).piles,200)
})
test('vehicle reads saved profile, missing parameters are explicitly assumptions',()=>{
  assert.equal(modelVehicle().assumed,true)
  const v=modelVehicle({batteryKwh:80,currentSoc:20,targetSoc:80,maxChargeKw:150})
  assert.equal(v.assumed,false)
  assert.equal(v.energy,48)
  assert.equal(modelVehicle({currentSoc:90,targetSoc:80}).energy,0)
})
test('identical demand is reproducible and extra chargers reduce a single-station bottleneck without mutating source',()=>{
  const f=station('a',{pileCount:2,powerKw:60}), original=structuredClone(f)
  const base=simulateCharging([stationModel(f)],{arrivals:100,duration:120})
  const after=simulateCharging([stationModel(f,{piles:20})],{arrivals:100,duration:120})
  assert.deepEqual(base,simulateCharging([stationModel(f)],{arrivals:100,duration:120}))
  assert.deepEqual(base.sessions.map(s=>[s.arrival,s.energy]),after.sessions.map(s=>[s.arrival,s.energy]))
  assert.ok(after.averageWait<base.averageWait)
  assert.ok(after.completed>base.completed)
  assert.deepEqual(f,original)
  for(const row of [base.rows[0],after.rows[0]]) assert.ok(row.utilization>=0&&row.utilization<=1)
})
test('queue accounting conserves arrivals, horizon energy is bounded, pause frame reflects actual sessions',()=>{
  const result=simulateCharging([stationModel(station('a',{pileCount:2,powerKw:60}))],{arrivals:70,duration:60})
  assert.equal(result.arrivals,result.sessions.length+result.unserved)
  const frame=simulationFrame(result,60)
  assert.equal(frame.charging.length+frame.waiting.length+frame.completed,result.sessions.length)
  assert.equal(frame.completed,result.completed)
  assert.ok(result.energy<=2*60*.8*.9)
  assert.equal(simulationFrame(result,0).charging.length,0)
  assert.equal(simulateCharging([], {arrivals:60,duration:60}).unserved,60)
  const zero=simulateCharging([stationModel(station('a'))],{arrivals:0})
  assert.equal(zero.energy,0);assert.equal(zero.averageWait,0)
})
test('removing all capacity is not described as an improvement in waiting',()=>{
  const model=stationModel(station('a',{pileCount:2,powerKw:60}))
  const before=simulateCharging([model],{arrivals:80})
  const after=simulateCharging([{...model,enabled:false}],{arrivals:80})
  assert.match(compareChargingScenarios(before,after),/未能分配/)
  assert.equal(after.completed,0)
  assert.equal(after.energy,0)
  assert.match(compareChargingScenarios({averageWait:10,completed:20,unserved:0},{averageWait:2,completed:10,unserved:0}),/完成车辆减少/)
})
