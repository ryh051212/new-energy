"""Bundle project GIS functions without importing the application/web server."""
import ast,hashlib,json,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];PROJECT=ROOT.parent
parts=['"""GIS helpers extracted from this project; generated by bundle_helpers.py."""','import math','from collections import Counter','from shapely.geometry import Point, Polygon, LineString','from shapely.ops import unary_union, polygonize']
selection={
 'backend/data/coordinate_transform.py':{'PI','A','EE','out_of_china','transform_lat','transform_lng','wgs84_to_gcj02','gcj02_to_wgs84'},
 'backend/data/osm_roads.py':{'ATTRIBUTION','LICENSE_URL','MOTOR_ROADS','length_m','road_direction','motor_access','normalize_roads'},
 'backend/core/siting_context.py':{'element_geometry'},
}
manifest=[]
for relative,names in selection.items():
 source=(PROJECT/relative).read_text(encoding='utf-8-sig');tree=ast.parse(source)
 for node in tree.body:
  selected=isinstance(node,ast.FunctionDef) and node.name in names or isinstance(node,ast.Assign) and any(isinstance(t,ast.Name) and t.id in names for t in node.targets)
  if selected:parts.append(ast.unparse(node))
 manifest.append({'project_source':relative,'sha256':hashlib.sha256(source.encode()).hexdigest(),'exported_symbols':sorted(names)})
(ROOT/'scripts/geo_helpers.py').write_text('\n\n'.join(parts)+'\n',encoding='utf-8')
(ROOT/'metadata/helper_sources.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
snapshots=['data/raw/amap-facilities.json','data/raw/amap-stations.json','data/raw/osm-roads-overpass.json','data/managed/station-equipment.json','data/managed/station-verification.json','data/processed/weidu-siting-context.geojson','data/processed/weidu-osm-roads.geojson','data/processed/weidu-osm-road-network.json']
for relative in snapshots:
 target=ROOT/'raw/input_snapshots'/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(PROJECT/relative,target)
print('Standalone GIS helpers and real input snapshots bundled. Synthetic input CSV is excluded.')
